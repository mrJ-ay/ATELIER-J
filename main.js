// DOM Elements
const visualImg = document.getElementById('visualImg');
const visualTitle = document.getElementById('visualTitle');
const visualDesc = document.getElementById('visualDesc');
const visualBadge = document.getElementById('visualBadge');
const visualLink = document.getElementById('visualLink');
const slideDots = document.getElementById('slideDots');
const prevBtn = document.getElementById('prevSlide');
const nextBtn = document.getElementById('nextSlide');

const featuredList = document.getElementById('featuredList');
const archiveGrid = document.getElementById('archiveGrid');
const filterTabs = document.querySelectorAll('.filter-tab');

let currentSlide = 0;
let slideInterval = null;

// Initialize Slider Indicators
function initSlider() {
  slideDots.innerHTML = sliderItems
    .map((_, idx) => `<button type="button" class="dot ${idx === 0 ? 'active' : ''}" data-idx="${idx}"></button>`)
    .join('');

  document.querySelectorAll('.dot').forEach((dot) => {
    dot.addEventListener('click', () => {
      goToSlide(parseInt(dot.dataset.idx, 10));
    });
  });

  prevBtn?.addEventListener('click', () => {
    goToSlide((currentSlide - 1 + sliderItems.length) % sliderItems.length);
  });

  nextBtn?.addEventListener('click', () => {
    goToSlide((currentSlide + 1) % sliderItems.length);
  });

  startAutoSlide();
}

function goToSlide(idx) {
  currentSlide = idx;
  const item = sliderItems[currentSlide];

  visualImg.style.opacity = '0';
  setTimeout(() => {
    visualImg.src = item.img;
    visualImg.alt = item.title;
    visualTitle.textContent = item.title;
    visualDesc.textContent = item.desc;
    visualBadge.textContent = item.badge;
    visualLink.href = item.url;
    visualImg.style.opacity = '1';
  }, 200);

  document.querySelectorAll('.dot').forEach((d, i) => {
    d.classList.toggle('active', i === currentSlide);
  });
}

function startAutoSlide() {
  if (slideInterval) clearInterval(slideInterval);
  slideInterval = setInterval(() => {
    goToSlide((currentSlide + 1) % sliderItems.length);
  }, 6000);
}

// Render Featured Exhibitions (간송미술관 s_exh 스타일 카드)
function renderFeatured() {
  const featured = artworks.filter((a) => a.isFeatured);
  featuredList.innerHTML = featured
    .map(
      (a) => `
    <article class="exh-card">
      <a href="${a.url}" target="_blank" rel="noopener" class="exh-link">
        <div class="exh-thumb">
          <img src="shots/${a.shot}" alt="${a.title}" loading="lazy" />
          <span class="exh-badge">${a.tag}</span>
        </div>
        <div class="exh-info">
          <div class="exh-meta">
            <span class="exh-no">${a.no}</span>
            <span class="exh-kind">${a.kind}</span>
          </div>
          <h3 class="exh-title">${a.title}</h3>
          <p class="exh-subtitle">${a.koreanTitle}</p>
          <p class="exh-desc">${a.summary}</p>
          <div class="exh-bottom">
            <span class="exh-period">${a.period}</span>
            <span class="exh-arrow">전시 관람하기 ↗</span>
          </div>
        </div>
      </a>
    </article>`
    )
    .join('');
}

// Render Archive Grid
let currentCategory = 'all';

function renderArchive() {
  const filtered = artworks.filter((a) => {
    return currentCategory === 'all' || a.category === currentCategory;
  });

  archiveGrid.innerHTML = filtered
    .map(
      (a) => `
    <article class="archive-item">
      <a href="${a.url}" target="_blank" rel="noopener" class="archive-link">
        <div class="archive-thumb">
          <img src="shots/${a.shot}" alt="${a.title}" loading="lazy" />
          <span class="archive-tag">${a.kind}</span>
        </div>
        <div class="archive-content">
          <span class="archive-no">${a.no}</span>
          <h4 class="archive-title">${a.title}</h4>
          <p class="archive-desc">${a.summary}</p>
        </div>
      </a>
    </article>`
    )
    .join('');
}

// Filter Tabs
filterTabs.forEach((btn) => {
  btn.addEventListener('click', () => {
    filterTabs.forEach((b) => b.classList.remove('active'));
    btn.classList.add('active');
    currentCategory = btn.dataset.cat;
    renderArchive();
  });
});

initSlider();
renderFeatured();
renderArchive();
